const ALL_AGENTS = ['codex', 'claude-code', 'copilot', 'cursor', 'gemini', 'generic'];

const readOnly = Object.freeze({
  filesystem: 'read',
  network: false,
  scripts: false,
  hooks: false,
  authentication: false,
});

function crux(id, name, category, description, instructions, options = {}) {
  return {
    id,
    name,
    category,
    description,
    kind: options.kind ?? 'skill',
    source: 'crux',
    status: options.status ?? 'recommended',
    agents: options.agents ?? ALL_AGENTS,
    permissions: options.permissions ?? readOnly,
    benefits: options.benefits ?? [description],
    useCases: options.useCases ?? [],
    instructions,
    tags: options.tags ?? [],
    required: options.required ?? false,
    explicitOnly: options.explicitOnly ?? false,
    tagline: options.tagline,
    documentation: options.documentation,
    diagram: options.diagram,
    intellectualProperty: options.intellectualProperty,
    version: '1.0.0',
    license: 'MIT',
  };
}

function external(id, name, category, description, sourceUrl, options = {}) {
  return {
    id,
    name,
    category,
    description,
    kind: options.kind ?? 'skill',
    source: 'external',
    status: options.status ?? 'optional',
    agents: options.agents ?? ALL_AGENTS,
    permissions: options.permissions ?? readOnly,
    benefits: options.benefits ?? [description],
    useCases: options.useCases ?? [],
    tags: options.tags ?? [],
    sourceUrl,
    installCommand: options.installCommand,
    version: 'provider-managed',
    license: options.license ?? 'See provider',
  };
}

